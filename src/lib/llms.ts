// llms.txt come lo scrive Yoast oggi (stessa struttura, stesse sezioni, stessi caratteri protetti).
// Yoast lo rigenera una volta a settimana; qui si rigenera ogni giorno dagli stessi dati.

/** Yoast scrive il file con il BOM in testa. */
const BOM = String.fromCharCode(0xfeff);

type Voce = { titolo: string; percorso: string; descrizione?: string };

/** I caratteri che Yoast protegge con la barra rovesciata nel Markdown. */
export const proteggi = (s: string) => s.replace(/[\\`*_{}[\]()#+\-.!|]/g, (c) => "\\" + c);

function sezione(nome: string, voci: Voce[], sito: string): string[] {
  if (!voci.length) return [];
  return [
    `## ${nome}`,
    ...voci.map((v) => `- [${proteggi(v.titolo)}](${sito}${v.percorso})${v.descrizione ? `: ${proteggi(v.descrizione)}` : ""}`),
    "",
  ];
}

export function testoLlms(
  sito: string,
  d: { articoli: Voce[]; pagine: Voce[]; categorie: Voce[]; tag: Voce[] },
): string {
  return [
    BOM + "# 🎮 Il Platinatore",
    "",
    "Generated by Yoast SEO v28.7, this is an llms.txt file, meant for consumption by LLMs.",
    "",
    ...sezione("Pagine", d.pagine, sito),
    ...sezione("Articoli", d.articoli, sito),
    ...sezione("Categorie", d.categorie, sito),
    ...sezione("Tag", d.tag, sito),
    "## Optional",
    `- [Sitemap index](${sito}/sitemap_index.xml)`,
    "",
  ].join("\n");
}
